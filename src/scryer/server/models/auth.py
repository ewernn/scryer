class User(Base, TimestampMixin, SoftDeleteMixin):
    __tablename__ = "users"
    __table_args__ = (
        # Partial unique: soft-deleted users free their email for reuse.
        Index(
            "ux_users_email_active",
            "email",
            unique=True,
            postgresql_where=text("archived_at IS NULL"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    email: Mapped[str] = mapped_column(String(320), nullable=False)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    display_name: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Relationships
    owned_workspaces: Mapped[list[Workspace]] = relationship(
        "Workspace", back_populates="owner", lazy="raise"
    )
    workspace_memberships: Mapped[list[WorkspaceMember]] = relationship(
        "WorkspaceMember", back_populates="user", lazy="raise"
    )
    project_memberships: Mapped[list[ProjectMember]] = relationship(
        "ProjectMember", back_populates="user", lazy="raise"
    )
    # Polymorphic-aware: only api_keys whose principal_kind='user' AND principal_user_id=self.id.
    # `lazy="raise"` forces explicit loading; `viewonly=True` because principal_kind is also
    # a column not just an FK.
    api_keys: Mapped[list[ApiKey]] = relationship(
        "ApiKey",
        primaryjoin=(
            "and_(User.id==foreign(ApiKey.principal_user_id), ApiKey.principal_kind=='user')"
        ),
        lazy="raise",
        viewonly=True,
    )


