class ApiKey(Base, TimestampMixin):
    """Programmatic auth credential. Polymorphic principal (User OR ServiceAccount).

    `key_hash` = sha256(full_key) — the input has 256 bits of entropy so a
    fast hash is sufficient; argon2 here would add ~50ms per request for no
    security benefit. Matches Stripe / GitHub / crates.io.

    See plan §6 (and notepad: investigator-recommended deviation from earlier
    bcrypt locking).
    """

    __tablename__ = "api_keys"
    __table_args__ = (
        # Polymorphic FK: exactly one of (user, service_account) must be set
        CheckConstraint(
            "(principal_user_id IS NOT NULL)::int + "
            "(principal_service_account_id IS NOT NULL)::int = 1",
            name="exactly_one_principal",
        ),
        # Discriminator must agree with which FK is populated
        CheckConstraint(
            "(principal_kind = 'user' AND principal_user_id IS NOT NULL) OR "
            "(principal_kind = 'service_account' AND principal_service_account_id IS NOT NULL)",
            name="principal_kind_matches_fk",
        ),
        Index("ix_api_keys_key_prefix", "key_prefix"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)

    # Polymorphic principal
    principal_kind: Mapped[PrincipalKind] = mapped_column(
        Enum(PrincipalKind, name="principal_kind", native_enum=False, length=32),
        nullable=False,
    )
    # ondelete=RESTRICT: don't silently lose audit trail when user is hard-deleted.
    # Since User uses SoftDeleteMixin, normal flow soft-deletes (RESTRICT not triggered).
    principal_user_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="RESTRICT"), nullable=True
    )
    principal_service_account_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("service_accounts.id", ondelete="RESTRICT"), nullable=True
    )

    # Display + verification
    key_prefix: Mapped[str] = mapped_column(String(32), nullable=False)
    key_hash: Mapped[str] = mapped_column(String(64), nullable=False)  # sha256 hex
    name: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Authorization
    scopes: Mapped[list[ApiScope]] = mapped_column(
        ARRAY(Enum(ApiScope, name="api_scope", native_enum=False, length=32)),
        nullable=False,
        default=list,
        server_default=text("'{}'"),
    )
    # allowed_ips removed v0 (deferred enforcement; CONVENTIONS: no fake support)

    # Lifecycle
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    last_used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Relationships (one populated based on principal_kind)
    user: Mapped[User | None] = relationship(
        "User",
        primaryjoin="ApiKey.principal_user_id==User.id",
        foreign_keys="[ApiKey.principal_user_id]",
        lazy="raise",
    )
    service_account: Mapped[ServiceAccount | None] = relationship(
        "ServiceAccount",
        foreign_keys="[ApiKey.principal_service_account_id]",
        lazy="raise",
    )


