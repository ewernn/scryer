class Invitation(Base, TimestampMixin):
    """Signup token. `token_hash` = sha256(token); high-entropy input so
    argon2/bcrypt buys nothing. See ApiKey docstring."""

    __tablename__ = "invitations"
    __table_args__ = (
        Index("ix_invitations_token_hash", "token_hash"),
        # Defensive: invites must have nonzero TTL at creation
        CheckConstraint("expires_at > created_at", name="ttl_positive"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False)  # sha256 hex
    email: Mapped[str | None] = mapped_column(String(320), nullable=True)
    workspace_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("workspaces.id", ondelete="CASCADE"), nullable=False
    )
    workspace_role: Mapped[WorkspaceRole] = mapped_column(
        Enum(WorkspaceRole, name="workspace_role", native_enum=False, length=32),
        nullable=False,
    )
    project_grants: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    invited_by: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )

    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    used_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    @property
    def status(self) -> InvitationStatus:
        """Computed; not stored. Queries that need to filter by status must
        use `WHERE` clauses on the underlying timestamp columns."""
        from scryer.server.models.base import utc_now

        if self.revoked_at is not None:
            return InvitationStatus.revoked
        if self.used_at is not None:
            return InvitationStatus.used
        if self.expires_at < utc_now():
            return InvitationStatus.expired
        return InvitationStatus.pending


