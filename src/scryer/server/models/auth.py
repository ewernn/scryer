class Workspace(Base, TimestampMixin, SoftDeleteMixin):
    """Plan §5: billing/team boundary; root of resource hierarchy.

    Slug history (`workspace_slugs`) enforces "no slug ever reclaimed" at the
    application layer (slug INSERT into workspaces also writes a row to
    workspace_slugs). DB-level enforcement (e.g., trigger) deferred to v1.
    """

    __tablename__ = "workspaces"
    __table_args__ = (
        UniqueConstraint("slug"),
        CheckConstraint("active_run_count >= 0", name="active_run_count_nonneg"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    slug: Mapped[str] = mapped_column(String(64), nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    owner_user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )

    # Plan §7: keep-alive counter for serverless wake-up
    active_run_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default=text("0")
    )

    owner: Mapped[User] = relationship("User", back_populates="owned_workspaces", lazy="raise")
    projects: Mapped[list[Project]] = relationship(
        "Project", back_populates="workspace", lazy="raise"
    )
    members: Mapped[list[WorkspaceMember]] = relationship(
        "WorkspaceMember", back_populates="workspace", lazy="raise"
    )
    service_accounts: Mapped[list[ServiceAccount]] = relationship(
        "ServiceAccount", back_populates="workspace", lazy="raise"
    )


