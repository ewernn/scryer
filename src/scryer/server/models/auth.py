"""Cluster 1: Identity + Org + Auth.

14 tables per plan §11:

- users, workspaces, workspace_slugs, projects, project_slugs
- workspace_members, project_members
- service_accounts, api_keys, api_key_usage
- invitations, credentials
- share_grants, budgets

**Enums use `native_enum=False`** (CHECK-constrained VARCHAR, NOT PG `CREATE TYPE`).
Reason: native enums break per-test schema isolation (enums are global; not
schema-scoped). Cost is small — Python enum still validates at the ORM layer.
Investigator-recommended.

**Polymorphic FK pattern** (api_keys.principal, budgets.principal):
two nullable FK cols + `principal_kind` discriminator + 2 CHECK constraints.
CHECK constraints are NOT autogenerated by Alembic — declared in
`__table_args__` and emitted manually in the migration.
"""

